enum VisitStatus {
  registered('Registered'),
  checkedIn('Checked In'),
  checkedOut('Checked Out');

  const VisitStatus(this.label);
  final String label;
  static VisitStatus parse(Object? value) => values.firstWhere(
    (s) => s.label == value,
    orElse: () => throw const FormatException('Unknown visitor status'),
  );
}

class Visitor {
  const Visitor({
    required this.id,
    required this.name,
    required this.mobile,
    this.email,
    required this.visitorType,
    required this.project,
    required this.purpose,
    required this.status,
    required this.createdAt,
    this.checkInTime,
    this.checkOutTime,
  });
  final String id, name, mobile, visitorType, project, purpose;
  final String? email;
  final VisitStatus status;
  final DateTime createdAt;
  final DateTime? checkInTime, checkOutTime;
  factory Visitor.fromJson(Map<String, dynamic> json) {
    String text(String key) {
      final value = json[key];
      if (value == null || value.toString().trim().isEmpty) {
        throw FormatException('Missing $key');
      }
      return value.toString();
    }

    DateTime? time(String key) => json[key] == null || json[key] == ''
        ? null
        : DateTime.parse(json[key].toString());
    return Visitor(
      id: text('id'),
      name: text('name'),
      mobile: text('mobile'),
      email: json['email'] as String?,
      visitorType: text('visitor_type'),
      project: text('project'),
      purpose: text('purpose'),
      status: VisitStatus.parse(json['status']),
      createdAt: DateTime.parse(text('created_at')),
      checkInTime: time('check_in_time'),
      checkOutTime: time('check_out_time'),
    );
  }
  Map<String, dynamic> toJson() => {
    'id': id,
    'name': name,
    'mobile': mobile,
    'email': email,
    'visitor_type': visitorType,
    'project': project,
    'purpose': purpose,
    'status': status.label,
    'created_at': createdAt.toUtc().toIso8601String(),
    'check_in_time': checkInTime?.toUtc().toIso8601String(),
    'check_out_time': checkOutTime?.toUtc().toIso8601String(),
  };
  Map<String, dynamic> transition(VisitStatus target, DateTime now) {
    if (status == VisitStatus.registered && target == VisitStatus.checkedIn) {
      return {
        'status': target.label,
        'check_in_time': now.toUtc().toIso8601String(),
      };
    }
    if (status == VisitStatus.checkedIn && target == VisitStatus.checkedOut) {
      return {
        'status': target.label,
        'check_out_time': now.toUtc().toIso8601String(),
      };
    }
    throw StateError('Cannot move from ${status.label} to ${target.label}.');
  }
}

bool sameLocalDay(DateTime? value, DateTime today) {
  if (value == null) return false;
  final local = value.toLocal();
  final day = today.toLocal();
  return local.year == day.year &&
      local.month == day.month &&
      local.day == day.day;
}

String parseVisitorQr(String value) {
  final id = value.trim();
  if (!RegExp(r'^[a-zA-Z0-9_-]{1,128}$').hasMatch(id)) {
    throw const FormatException(
      'Invalid visitor QR code. Scan a pass generated by this app.',
    );
  }
  return id;
}
